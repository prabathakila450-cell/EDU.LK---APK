  fun getSetsForSubject(grade: String, subject: String): List<FlashcardSetInfo> {
    val themes = getUnitThemesForSubject(grade, subject)
    return (1..15).map { setNum ->
      val start = (setNum - 1) * 20 + 1
      val end = setNum * 20
      val theme = themes.getOrElse(setNum - 1) { "විෂය ඒකක හා ප්‍රශ්නෝත්තර සංග්‍රහය - $setNum" }
      FlashcardSetInfo(
        setNumber = setNum,
        title = "කාණ්ඩය $setNum ($start - $end)",
        startCardNum = start,
        endCardNum = end,
        totalCards = 20,
        unitTheme = theme
      )
    }
  }

  fun getFlashcards(grade: String, subject: String, setNumber: Int? = null): List<FlashcardDeckItem> {
    val all300 = generate300Cards(grade, subject)
    return if (setNumber != null && setNumber in 1..15) {
      all300.filter { it.setNumber == setNumber }
    } else {
      all300
    }
  }

