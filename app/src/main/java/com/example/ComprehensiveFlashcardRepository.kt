  // Generates 300 unique, curriculum-aligned flashcard items
  private fun generate300Cards(grade: String, subject: String): List<FlashcardDeckItem> {
    val themes = getUnitThemesForSubject(grade, subject)
    val list = ArrayList<FlashcardDeckItem>(300)

    for (setNum in 1..15) {
      val theme = themes.getOrElse(setNum - 1) { "විෂය ඒකකය - $setNum" }
      val cardsInSet = generate20CardsForSet(grade, subject, setNum, theme)
      list.addAll(cardsInSet)
    }

    return list
  }

  private fun generate20CardsForSet(
    grade: String,
    subject: String,
    setNum: Int,
    theme: String
  ): List<FlashcardDeckItem> {
    val baseIndex = (setNum - 1) * 20

    // Specific curated question-answer bank generator per subject, grade, and set
    return (1..20).map { cardInSet ->
      val globalIdx = baseIndex + cardInSet
      val (q, a, tip, fact) = getCardContent(grade, subject, setNum, cardInSet, globalIdx, theme)
      FlashcardDeckItem(
        id = "fc_${grade}_${subject.hashCode()}_${globalIdx}",
        grade = grade,
        subject = subject,
        setNumber = setNum,
        cardIndexInSet = cardInSet,
        globalIndex = globalIdx,
        questionFront = q,
        answerBack = a,
        explanationTip = tip,
        formulaOrFact = fact,
        unitCategory = theme
      )
    }
  }

  private fun getCardContent(
    grade: String,
    subject: String,
    setNum: Int,
    cardInSet: Int,
    globalIdx: Int,
    theme: String
  ): CardContentTuple {
    // 1. Science
    if (subject.contains("විද්‍යාව")) {
      return getScienceCardContent(grade, setNum, cardInSet, globalIdx, theme)
    }
    // 2. Mathematics
    if (subject.contains("ගණිතය")) {
      return getMathCardContent(grade, setNum, cardInSet, globalIdx, theme)
    }
    // 3. History
    if (subject.contains("ඉතිහාසය")) {
      return getHistoryCardContent(grade, setNum, cardInSet, globalIdx, theme)
    }
    // 4. Buddhism
    if (subject.contains("බුද්ධ") || subject.contains("ආගම")) {
      return getBuddhismCardContent(grade, setNum, cardInSet, globalIdx, theme)
    }
    // 5. Sinhala
    if (subject.contains("සිංහල")) {
      return getSinhalaCardContent(grade, setNum, cardInSet, globalIdx, theme)
    }
    // 6. English
    if (subject.contains("English") || subject.contains("ඉංග්‍රීසි")) {
      return getEnglishCardContent(grade, setNum, cardInSet, globalIdx, theme)
    }
    // 7. Commerce
    if (subject.contains("වාණිජ") || subject.contains("ගිණුම්")) {
      return getCommerceCardContent(grade, setNum, cardInSet, globalIdx, theme)
    }
    // 8. ICT
    if (subject.contains("ICT") || subject.contains("තොරතුරු")) {
      return getIctCardContent(grade, setNum, cardInSet, globalIdx, theme)
    }
    // 9. Geography
    if (subject.contains("භූගෝල")) {
      return getGeographyCardContent(grade, setNum, cardInSet, globalIdx, theme)
    }
    // 10. Default / Civics / Agriculture / Health
    return getDefaultSubjectCardContent(grade, subject, setNum, cardInSet, globalIdx, theme)
  }

